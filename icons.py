_ICON_CACHE = {}

def get_pixmap(name: str, color: str = "#EDF1F7", size: int = 18) -> QPixmap:
    cache_key = (name, color, size)
    if cache_key in _ICON_CACHE:
        return _ICON_CACHE[cache_key]

    body = LUCIDE_PATHS.get(name, LUCIDE_PATHS["download"])
    svg_str = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" '
        f'viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="2" '
        f'stroke-linecap="round" stroke-linejoin="round">{body}</svg>'
    )
    renderer = QSvgRenderer(QByteArray(svg_str.encode("utf-8")))
    pixmap = QPixmap(size, size)
    pixmap.fill(QColor(0, 0, 0, 0))
    painter = QPainter(pixmap)
    renderer.render(painter)
    painter.end()

    _ICON_CACHE[cache_key] = pixmap
    return pixmap


def get_icon(name: str, color: str = "#EDF1F7", size: int = 18) -> QIcon:
    return QIcon(get_pixmap(name, color, size))
